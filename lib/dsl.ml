open Types

(* Combinators, built with local opens — no top-level `open` *)
let attribute ty name = Expr.(Var (ty, name))
let uniform ty name = Expr.(Var (ty, name))
let ( +. ) a b = Expr.(Add (a, b))
let ( -. ) a b = Expr.(Sub (a, b))
let ( *. ) a b = Expr.(Mul (a, b))
let ( /. ) a b = Expr.(Div (a, b))
let f x = Expr.(Float_const x)
let vec3 a b c = Expr.(Vec3_const (a, b, c))
let vec4 a b c d = Expr.(Vec4_const (a, b, c, d))
let vec4_of_vec3 v w = Expr.(Vec4_of_vec3 (v, w))
let mat4_mul_vec4 m v = Expr.(Mat_mul_vec (m, v))
let dot a b = Expr.(Dot (a, b))
let normalize v = Expr.(Normalize v)
let assign r e = Stmt.(Assign (r, e))
let if_ c t e = Stmt.(If (c, t, e))
